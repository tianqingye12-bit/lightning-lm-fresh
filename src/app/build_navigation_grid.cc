// Re-render cleaned IMU-frame keyframes synchronously, retaining only the current cloud.
#include <gflags/gflags.h>
#include <glog/logging.h>
#include <pcl/io/pcd_io.h>
#include <yaml-cpp/yaml.h>
#include <filesystem>
#include <fstream>
#include <iomanip>
#include <set>
#include <sstream>
#include <stdexcept>
#include "common/keyframe.h"
#include "core/g2p5/g2p5.h"
#include "core/maps/navigation_grid.h"

DEFINE_string(config, "", "Validated sensor/G2P5 YAML");
DEFINE_string(input_frames, "", "Quoted frame manifest generated by build_static_navigation.py");
DEFINE_string(frame_contract, "", "Version 2 map_frames.yaml");
DEFINE_string(output, "", "New navigation directory (created by wrapper)");

int main(int argc, char** argv) {
    google::InitGoogleLogging(argv[0]);
    FLAGS_logtostderr = true;
    google::ParseCommandLineFlags(&argc, &argv, true);
    try {
        using namespace lightning;
        if (FLAGS_config.empty() || FLAGS_input_frames.empty() || FLAGS_output.empty())
            throw std::invalid_argument("config, input_frames, frame_contract and output are required");
        if (std::filesystem::exists(FLAGS_output+"/map.yaml") || std::filesystem::exists(FLAGS_output+"/map.pgm"))
            throw std::invalid_argument("refusing to overwrite navigation grid");
        const auto meta = YAML::LoadFile(FLAGS_frame_contract);
        if (meta["format_version"].as<int>() != 2 || meta["keyframe_pose_frame"].as<std::string>() != "imu" ||
            meta["keyframe_cloud_frame"].as<std::string>() != "imu") throw std::invalid_argument("expected IMU v2 contract");
        const auto values = meta["T_imu_lidar"].as<std::vector<double>>();
        if (values.size() != 16) throw std::invalid_argument("invalid extrinsic dimensions");
        Eigen::Matrix4d matrix;
        for (int i=0; i<16; ++i) matrix(i/4, i%4) = values[i];
        const Eigen::Matrix3d rotation = matrix.topLeftCorner<3,3>();
        if (!matrix.allFinite() || !matrix.row(3).isApprox(Eigen::RowVector4d(0,0,0,1), 1e-6) ||
            !(rotation.transpose()*rotation).isApprox(Eigen::Matrix3d::Identity(), 1e-4) ||
            std::abs(rotation.determinant()-1) > 1e-4) throw std::invalid_argument("invalid rigid extrinsic");
        const SE3 T_imu_lidar(Quatd(rotation), matrix.topRightCorner<3,1>());
        g2p5::G2P5::Options options;
        options.online_mode_ = false;
        options.retain_offline_keyframes_ = false;
        options.max_grid_cells_ = 8000000;
        options.verbose_ = false;
        g2p5::G2P5 renderer(options);
        renderer.Init(FLAGS_config);
        renderer.SetParallelRendering(false);
        std::ifstream input(FLAGS_input_frames);
        if (!input) throw std::runtime_error("cannot read frame manifest");
        std::string line;
        std::set<long long> ids;
        std::size_t count = 0;
        while (std::getline(input, line)) {
            if (line.empty()) continue;
            std::istringstream row(line);
            long long id;
            double timestamp, x,y,z,qx,qy,qz,qw;
            std::string path, extra;
            if (!(row >> id >> timestamp >> x >> y >> z >> qx >> qy >> qz >> qw >> std::quoted(path)) ||
                (row >> extra) || id < 0 || !ids.insert(id).second)
                throw std::invalid_argument("invalid/duplicate frame manifest row");
            Quatd q(qw,qx,qy,qz);
            if (!std::isfinite(timestamp) || !Vec3d(x,y,z).allFinite() || !q.coeffs().allFinite() || q.norm() < 1e-12)
                throw std::invalid_argument("nonfinite frame pose");
            q.normalize();
            CloudPtr cloud(new PointCloudType);
            if (pcl::io::loadPCDFile(path, *cloud) < 0) throw std::runtime_error("cannot read "+path);
            CloudPtr finite(new PointCloudType);
            finite->reserve(cloud->size());
            for (const auto& point : cloud->points) if (point.getVector3fMap().allFinite()) finite->push_back(point);
            if (finite->empty()) continue;
            NavState state;
            state.timestamp_ = timestamp;
            state.SetPose(SE3(q, Vec3d(x,y,z)));
            renderer.PushKeyframe(std::make_shared<Keyframe>(static_cast<unsigned long>(id), finite, state, T_imu_lidar));
            if (++count % 20 == 0) LOG(INFO) << "rebuilt navigation grid from " << count << " cleaned frames";
        }
        const auto map = renderer.GetNewestMap();
        if (!map || !count) throw std::runtime_error("no nonempty cleaned frames");
        const auto occupancy = map->ToROS();
        navigation::GridSpec spec;
        spec.width = occupancy.info.width; spec.height = occupancy.info.height;
        spec.resolution = occupancy.info.resolution;
        spec.origin = {occupancy.info.origin.position.x, occupancy.info.origin.position.y, 0};
        navigation::SaveGrid(FLAGS_output, spec, occupancy.data);
        LOG(INFO) << "saved " << spec.width << 'x' << spec.height << " navigation grid at " << spec.resolution << " m";
        return 0;
    } catch (const std::exception& error) {
        LOG(ERROR) << error.what();
        return 1;
    }
}
